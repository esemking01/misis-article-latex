def female_surname(s: str) -> str:
    if s in SURNAMES_NEUTRAL:
        return s
    if s.endswith("ский"):
        return s[:-4] + "ская"
    return s + "а"  # -ов, -ев, -ёв, -ин -> -ова, -ева, -ёва, -ина
